import fs from 'fs-extra';
import path from 'path';
import { type WorkflowMode } from '../config';
import {
  type PathContext,
  mergeGeneratedBlock,
  parseFrontmatter,
  resolvePlaceholders,
  setFrontmatterFields,
  stripFrontmatter,
} from '../markdown';
import {
  CONFIG_DIR,
  NEUTRAL_RULES_DIR,
  includeCoreRule,
  installRules,
  installSkills,
  installedSkillNames,
  readAgents,
  readCommands,
  replaceManagedEntries,
} from './content';
import { CORE_SOURCE, STACKS_SOURCE } from '../paths';

const CLAUDE_CTX: PathContext = { skills: '.claude/skills', rules: NEUTRAL_RULES_DIR, config: CONFIG_DIR };

// Skills that should run in an isolated subagent when invoked from Claude Code.
const FORKED_SKILLS: Record<string, string> = { contrarian: 'contrarian' };

// Claude Code loads skills natively from .claude/skills/<name>/SKILL.md and exposes each
// as /<name>. Commands are installed only as aliases whose name differs from a skill
// (e.g. /review -> code-review), because a skill wins over a command with the same name.
export async function installClaude(projectRoot: string, stacks: string[], mode: WorkflowMode): Promise<void> {
  const claudeDir = path.join(projectRoot, '.claude');
  const skillsDir = path.join(claudeDir, 'skills');

  await installSkills(skillsDir, stacks, mode, CLAUDE_CTX);
  if (mode === 'structured') {
    for (const [skill, agent] of Object.entries(FORKED_SKILLS)) {
      const skillPath = path.join(skillsDir, skill, 'SKILL.md');
      if (!(await fs.pathExists(skillPath))) continue;
      const content = await fs.readFile(skillPath, 'utf-8');
      await fs.writeFile(skillPath, setFrontmatterFields(content, { context: 'fork', agent }), 'utf-8');
    }
  }

  const skillNames = await installedSkillNames(stacks, mode);
  const commandsDir = path.join(claudeDir, 'commands');
  await replaceManagedEntries(commandsDir, async () => {
    const written: string[] = [];
    for (const command of await readCommands(mode)) {
      if (skillNames.has(command.name)) continue;
      await fs.writeFile(path.join(commandsDir, `${command.name}.md`), resolvePlaceholders(command.content, CLAUDE_CTX), 'utf-8');
      written.push(`${command.name}.md`);
    }
    return written;
  });

  const agentsDir = path.join(claudeDir, 'agents');
  await replaceManagedEntries(agentsDir, async () => {
    const written: string[] = [];
    for (const agent of await readAgents(mode)) {
      await fs.writeFile(path.join(agentsDir, `${agent.name}.md`), resolvePlaceholders(agent.content, CLAUDE_CTX), 'utf-8');
      written.push(`${agent.name}.md`);
    }
    return written;
  });

  await installRules(path.join(projectRoot, NEUTRAL_RULES_DIR), stacks, mode, CLAUDE_CTX);
  await generateClaudeMd(projectRoot, stacks, mode);

  // Before 1.7 Claude Code skills were copied to .agent-runway/skills and read via commands.
  await fs.remove(path.join(projectRoot, '.agent-runway', 'skills'));
}

const CLAUDE_START = '<!-- agent-runway:claude:start -->';
const CLAUDE_END = '<!-- agent-runway:claude:end -->';

// Generates the Agent Runway block of CLAUDE.md. alwaysApply rules are inlined; the rest
// get a one-line summary pointing at .agent-runway/rules/. User content outside the
// marked block is preserved.
export async function generateClaudeMd(projectRoot: string, stacks: string[], mode: WorkflowMode): Promise<void> {
  const sections: string[] = [
    '# Agent Runway - Project Rules\n',
    '<!-- Generated by Agent Runway. Re-run `agent-runway update` to refresh. -->',
    '<!-- Full rule content is in `.agent-runway/rules/` for rules not inlined here. -->\n',
    'Agent Runway workflows are installed as skills in `.claude/skills/` and can be invoked as `/<skill>` (for example `/start`). Project memory, specs, logs and docs live in `.agent-runway/`.\n',
  ];

  const coreRulesDir = path.join(CORE_SOURCE, 'rules');
  const coreRuleFiles = (await fs.readdir(coreRulesDir)).filter((f) => f.endsWith('.mdc') && includeCoreRule(f, mode)).sort();
  for (const file of coreRuleFiles) {
    const content = await fs.readFile(path.join(coreRulesDir, file), 'utf-8');
    const fm = parseFrontmatter(content);
    const title = file.replace('.mdc', '');
    if (fm.alwaysApply === true) {
      sections.push(`## ${title}\n\n${resolvePlaceholders(stripFrontmatter(content), CLAUDE_CTX)}\n`);
    } else {
      sections.push(`## ${title}\n\n> **${fm.description || title}**\n> Full rule: \`.agent-runway/rules/${file}\`\n`);
    }
  }

  for (const stack of stacks) {
    const stackPath = path.join(STACKS_SOURCE, stack);
    if (!(await fs.pathExists(stackPath))) continue;
    const mdcFiles = (await fs.readdir(stackPath)).filter((f) => f.endsWith('.mdc')).sort();
    if (mdcFiles.length === 0) continue;

    sections.push(`## Stack: ${stack}\n`);
    for (const file of mdcFiles) {
      const fm = parseFrontmatter(await fs.readFile(path.join(stackPath, file), 'utf-8'));
      sections.push(`### ${file.replace('.mdc', '')}\n\n> **${fm.description || file}**\n> Full rule: \`.agent-runway/rules/${file}\`\n`);
    }
  }

  const claudeMdPath = path.join(projectRoot, 'CLAUDE.md');
  const existing = (await fs.pathExists(claudeMdPath)) ? await fs.readFile(claudeMdPath, 'utf-8') : null;
  const merged = mergeGeneratedBlock(existing, sections.join('\n'), CLAUDE_START, CLAUDE_END, (content) =>
    content.startsWith('# Agent Runway - Project Rules') && content.includes('Generated by Agent Runway')
  );
  await fs.writeFile(claudeMdPath, merged, 'utf-8');
}
