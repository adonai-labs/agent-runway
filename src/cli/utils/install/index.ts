const SCAFFOLD_DIRS = ['memory', 'specs', 'config', 'workflows', 'logs', 'docs'];

// Installs or refreshes every target in the config, then the project scaffold.
// Shared by init, update, add, remove and upgrade so they cannot drift apart.
export async function installFromConfig(projectRoot: string, config: Config, isGlobal = false): Promise<void> {
  const mode = normalizeWorkflowMode(config.mode);
  const targets = isGlobal ? (['cursor'] as InstallTarget[]) : config.targets;

  // Move pre-1.7 Cursor config files before the Cursor install replaces that folder.
  if (!isGlobal) await migrateLegacyCursorConfig(projectRoot);

  if (targets.includes('cursor')) await installCursor(getCursorDir(projectRoot, isGlobal), config.stacks, mode, isGlobal);
  if (targets.includes('claude')) await installClaude(projectRoot, config.stacks, mode);
  if (targets.includes('vscode')) await installVscode(projectRoot, config.stacks, mode);

  await ensureProjectScaffold(projectRoot, targets, isGlobal);
  if (!isGlobal) await installStackSpecTemplates(projectRoot, config.stacks);
}

async function migrateLegacyCursorConfig(projectRoot: string): Promise<void> {
  const legacyDir = path.join(projectRoot, '.cursor', 'config');
  if (!(await fs.pathExists(legacyDir))) return;
  await fs.copy(legacyDir, path.join(projectRoot, CONFIG_DIR), { overwrite: false, errorOnExist: false });
  await fs.remove(legacyDir);
}

// Creates the .agent-runway/ artifact layer. Templates are copied with overwrite:false,
// so memory, docs and config the team has edited are never replaced.
export async function ensureProjectScaffold(projectRoot: string, targets: InstallTarget[], isGlobal = false): Promise<void> {
  const agentRunwayDir = getAgentRunwayDir(projectRoot);
  for (const dir of SCAFFOLD_DIRS) await fs.ensureDir(path.join(agentRunwayDir, dir));

  for (const [source, dest] of [
    ['memory', 'memory'],
    ['docs', 'docs'],
    ['config', 'config'],
  ]) {
    const sourceDir = path.join(CORE_SOURCE, source);
    if (await fs.pathExists(sourceDir)) {
      await copyTemplates(sourceDir, path.join(agentRunwayDir, dest));
    }
  }

  await generateAgentsMd(projectRoot, targets, isGlobal);
}

async function copyTemplates(source: string, dest: string): Promise<void> {
  for (const entry of await fs.readdir(source, { withFileTypes: true })) {
    const from = path.join(source, entry.name);
    const to = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      await fs.ensureDir(to);
      await copyTemplates(from, to);
    } else if (!(await fs.pathExists(to))) {
      const content = await fs.readFile(from, 'utf-8');
      await fs.writeFile(to, resolvePlaceholders(content, { skills: '{{skills}}', rules: '{{rules}}', config: CONFIG_DIR }), 'utf-8');
    }
  }
}

const AGENTS_START = '<!-- agent-runway:agents:start -->';
const AGENTS_END = '<!-- agent-runway:agents:end -->';

const SKILL_LOCATIONS: Record<InstallTarget, string> = {
  cursor: '`.cursor/skills/` (Cursor)',
  claude: '`.claude/skills/` (Claude Code)',
  vscode: '`.github/skills/` (VS Code Copilot)',
};

// AGENTS.md is a neutral entrypoint for any coding agent; only its marked block is generated.
export async function generateAgentsMd(projectRoot: string, targets: InstallTarget[], isGlobal = false): Promise<void> {
  const agentsMdPath = path.join(projectRoot, 'AGENTS.md');
  const existing = (await fs.pathExists(agentsMdPath)) ? await fs.readFile(agentsMdPath, 'utf-8') : null;
  const cursorRoot = isGlobal ? '~/.cursor' : '.cursor';
  const rulesLocation = targets.some((t) => t !== 'cursor') ? '`.agent-runway/rules/`' : `\`${cursorRoot}/rules/\``;
  const skillLocation = (t: InstallTarget) =>
    t === 'cursor' ? `\`${cursorRoot}/skills/\` (Cursor)` : SKILL_LOCATIONS[t];

  const generated = [
    '# Agent Runway Instructions',
    '',
    '<!-- Generated by Agent Runway. Re-run `agent-runway update` to refresh this block. -->',
    '',
    '## Operating Model',
    '',
    '- Use Agent Runway artifacts as the project delivery context.',
    '- Start by understanding the problem, expected behavior, boundaries, and evidence plan before implementation.',
    '- Prefer Test-Driven Delivery for behavior changes: failing evidence, smallest implementation, refactor, recorded validation.',
    '- Use Narrative Delivery for medium or large work: context, intent, change, evidence, remaining work.',
    '- Treat optional graph/brain-context providers as evidence sources only; verify against repository artifacts.',
    '',
    '## Where To Look',
    '',
    `- Skills: ${targets.map(skillLocation).join(', ')}`,
    `- Rules: ${rulesLocation}`,
    '- Memory: `.agent-runway/memory/`',
    '- Specs and tickets: `.agent-runway/specs/`',
    '- Logs, reviews, checkpoints, and autonomous runs: `.agent-runway/logs/`',
    '- Project docs and ADRs: `.agent-runway/docs/`',
    '- Workflow configuration: `.agent-runway/config/`',
    '',
    '## Engineering Defaults',
    '',
    '- Follow SOLID, DRY, clean architecture, secure-by-default, and explicit error handling guidance from the installed rules.',
    '- Keep functions focused; functions over 60 lines should trigger review or extraction unless intentionally simple.',
    '- Keep files/classes cohesive; 600 lines is a warning zone and 800 lines requires strong justification except for generated/declarative files.',
    '- Do not edit generated Agent Runway framework files directly. Put project decisions in memory, docs, ADRs, specs, or tickets.',
    '',
    '## Validation',
    '',
    '- Run the smallest relevant build/test/lint/typecheck suite after changes.',
    '- If validation cannot run, record why and name the residual risk.',
    '- Preserve user-authored code and unrelated worktree changes.',
    '',
  ].join('\n');

  await fs.writeFile(agentsMdPath, mergeGeneratedBlock(existing, generated, AGENTS_START, AGENTS_END), 'utf-8');
}
